# 2. Define Gemini embedding function
def get_gemini_embedding(text):
    """Generate high-quality 768-dimension vector embedding using text-embedding-004 or fallback."""
    for model_name in ["models/text-embedding-004", "models/gemini-embedding-001", "models/embedding-001"]:
        try:
            response = genai.embed_content(
                model=model_name,
                content=text,
                task_type="retrieval_document"
            )
            return response['embedding']
        except Exception as e:
            err_str = str(e).lower()
            if "not found" in err_str or "404" in err_str or "not supported" in err_str:
                # Silently try next fallback model
                continue
            print(f"Embedding error with {model_name}: {e}")
            break
            
    # Return 768-dimension zero array as safety backup so seeder does not fully crash
    return [0.0] * 768

