def download_targeted_pdfs(markdown_urls, save_directory, keywords):
    if not os.path.exists(save_directory):
        os.makedirs(save_directory)

    headers = {'User-Agent': 'Mozilla/5.0'}
    total_downloaded = 0

    for url in markdown_urls:
        print(f"\nFetching list from: {url.split('/')[-1]}")
        response = requests.get(url)

        if response.status_code != 200:
            print("Failed to fetch markdown.")
            continue

        # Regex to capture BOTH the Book Title (Group 1) and the URL (Group 2)
        # Format: [Book Title](https://link.com/book.pdf)
        matches = re.findall(r'\[(.*?)\]\((https?://[^\)]+)\)', response.text)

        for title, link in matches:
            # Check if it's a PDF AND if the title matches our roadmap keywords
            title_lower = title.lower()
            if '.pdf' in link.lower() and any(keyword in title_lower for keyword in keywords):

                # Clean up filename
                filename = link.split('/')[-1].split('?')[0]
                if not filename.endswith('.pdf'):
                    filename += '.pdf'

                filepath = os.path.join(save_directory, filename)

                # Skip if we already downloaded it
                if os.path.exists(filepath):
                    continue

                print(f"Match found: '{title}'")
                print(f" -> Downloading: {filename}")

                try:
                    pdf_response = requests.get(link, stream=True, timeout=15, headers=headers)
                    if pdf_response.status_code == 200:
                        with open(filepath, 'wb') as f:
                            for chunk in pdf_response.iter_content(chunk_size=1024):
                                f.write(chunk)
                        total_downloaded += 1
                    else:
                        print(f"    x Server rejected: {pdf_response.status_code}")
                except Exception as e:
                    print(f"    x Download failed: {e}")

    print(f"\nTargeted scraping complete. Downloaded {total_downloaded} new conceptual PDFs.")

