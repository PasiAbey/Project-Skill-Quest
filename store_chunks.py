def download_pdfs_from_github_markdown(markdown_url, save_directory):
    if not os.path.exists(save_directory):
        os.makedirs(save_directory)

    print("Fetching markdown file...")
    response = requests.get(markdown_url)

    if response.status_code != 200:
        print(f"Failed to fetch markdown. Status code: {response.status_code}")
        return

    markdown_text = response.text

    # 1. Extract ALL links from the markdown file
    all_links = re.findall(r'\[.*?\]\((https?://[^\)]+)\)', markdown_text)

    # 2. Filter only the links that contain '.pdf' (handles query parameters)
    pdf_links = [link for link in all_links if '.pdf' in link.lower()]

    # Remove duplicates
    pdf_links = list(set(pdf_links))

    print(f"Found {len(pdf_links)} PDF links. Starting download...")

    # 3. Download each PDF (Limiting to first 10 for testing)
    for link in pdf_links:
        try:
            # Clean up the filename so it saves properly
            filename = link.split('/')[-1].split('?')[0]
            if not filename.endswith('.pdf'):
                filename += '.pdf'

            filepath = os.path.join(save_directory, filename)

            print(f"Downloading: {filename}")

            # Using a custom User-Agent to prevent academic servers from blocking the script
            headers = {'User-Agent': 'Mozilla/5.0'}
            pdf_response = requests.get(link, stream=True, timeout=15, headers=headers)

            if pdf_response.status_code == 200:
                with open(filepath, 'wb') as f:
                    for chunk in pdf_response.iter_content(chunk_size=1024):
                        f.write(chunk)
            else:
                print(f"  -> Server returned status {pdf_response.status_code}")

        except Exception as e:
            print(f"  -> Failed to download {link}: {e}")

